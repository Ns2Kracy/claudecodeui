import type { IRoutingNineRouterClient } from "@/shared/interfaces.js";
import type {
	RoutingClientCredentials,
	RoutingSettingsDetails,
} from "@/shared/types.js";
import { AppError } from "@/shared/utils.js";

import type {
	CreateRoutingApiKeyAccountInput,
	CreateRoutingProviderNodeInput,
	RoutingAccountView,
	RoutingModelView,
	RoutingOAuthPollingStateView,
	RoutingRuntimeView,
	RoutingSettingsView,
	UpdateRoutingAccountInput,
	UpdateRoutingProviderNodeInput,
	ValidateRoutingProviderNodeInput,
} from "../../../shared/routing.js";
import { emptyRoutingSettingsView } from "../../../shared/routing.js";

import type { createRoutingOAuthService } from "./routing-oauth.service.js";
import type {
	NineRouterInternalCredentials,
	NineRouterSidecarStatus,
} from "./nine-router-sidecar.service.js";

type RuntimeCredentialsProvider = {
	getStatus(): NineRouterSidecarStatus;
	refresh?(): Promise<NineRouterSidecarStatus>;
	getInternalCredentials(): NineRouterInternalCredentials;
};

type RoutingServiceDependencies = {
	runtime: RuntimeCredentialsProvider;
	clientFactory(
		credentials: RoutingClientCredentials,
	): IRoutingNineRouterClient;
	oauth?: ReturnType<typeof createRoutingOAuthService>;
	now?: () => Date;
};

function safeOperationFailure(): AppError {
	return new AppError("The Router operation failed", {
		code: "ROUTING_OPERATION_FAILED",
		statusCode: 502,
	});
}

function configurationInvalid(): AppError {
	return new AppError("The Router configuration is invalid", {
		code: "ROUTING_CONFIGURATION_INVALID",
		statusCode: 500,
	});
}

function runtimeUnavailable(): AppError {
	return new AppError("The Router is unavailable", {
		code: "ROUTING_RUNTIME_UNAVAILABLE",
		statusCode: 409,
	});
}

function safeAppError(error: unknown): AppError {
	return error instanceof AppError ? error : safeOperationFailure();
}

function runtimeView(
	status: NineRouterSidecarStatus,
	checkedAt: string,
): RoutingRuntimeView {
	const defaults = emptyRoutingSettingsView().runtime;
	const state = status.state;
	return {
		mode: "sidecar",
		status: state,
		version: status.version,
		lastCheckedAt: checkedAt,
		lastError: status.lastError,
		capabilities:
			state === "ready"
				? {
						readAccounts: true,
						writeApiKeyAccounts: true,
						testAccounts: true,
						readRoutes: true,
						writeRoutes: true,
						readUsage: false,
						claudeRuntime: true,
						codexRuntime: true,
						openCodeRuntime: true,
						cursorRuntime: false,
					}
				: { ...defaults.capabilities },
	};
}

/**
 * Used by routing module assembly and focused tests to build the user-scoped
 * sidecar-backed routing workflow. It never reads user-supplied 9router connection
 * rows or secure-storage credentials; all management clients use supervisor
 * credentials generated by CloudCLI.
 */
export function createRoutingService(dependencies: RoutingServiceDependencies) {
	const now = dependencies.now ?? (() => new Date());
	const modelSnapshotTtlMs = 5 * 60 * 1_000;
	const modelSnapshots = new Map<
		string,
		{ models: RoutingModelView[]; expiresAt: number }
	>();
	let modelSnapshotGeneration = 0;
	const pendingModelRequests = new Map<
		string,
		{ generation: number; request: Promise<RoutingModelView[]> }
	>();

	const expireModelSnapshots = (): void => {
		modelSnapshotGeneration += 1;
		for (const snapshot of modelSnapshots.values()) snapshot.expiresAt = 0;
	};

	async function refreshRuntimeIfUnavailable(): Promise<NineRouterSidecarStatus> {
		const status = dependencies.runtime.getStatus();
		if (status.state === "ready" || !dependencies.runtime.refresh)
			return status;
		try {
			return await dependencies.runtime.refresh();
		} catch {
			return dependencies.runtime.getStatus();
		}
	}

	function credentialsForRuntime(
		requireReady: boolean,
	): RoutingClientCredentials {
		const status = dependencies.runtime.getStatus();
		if (requireReady && status.state !== "ready") throw runtimeUnavailable();
		if (!status.origin) throw configurationInvalid();
		const credentials = dependencies.runtime.getInternalCredentials();
		return {
			baseUrl: status.origin,
			adminPassword: credentials.initialPassword,
			dataPlaneKey: credentials.dataPlaneKey,
		};
	}

	function clientForRuntime(): IRoutingNineRouterClient {
		try {
			return dependencies.clientFactory(credentialsForRuntime(true));
		} catch (error) {
			throw safeAppError(error);
		}
	}

	function clientForManagement(): IRoutingNineRouterClient {
		try {
			return dependencies.clientFactory(credentialsForRuntime(false));
		} catch (error) {
			throw safeAppError(error);
		}
	}

	async function callSafely<T>(operation: () => Promise<T>): Promise<T> {
		try {
			return await operation();
		} catch (error) {
			throw safeAppError(error);
		}
	}

	async function modelsForAccount(
		client: IRoutingNineRouterClient,
		account: RoutingAccountView,
		forceRefresh: boolean,
	): Promise<RoutingModelView[]> {
		const snapshot = modelSnapshots.get(account.id);
		if (!forceRefresh && snapshot && snapshot.expiresAt > now().getTime()) {
			return snapshot.models;
		}

		const generation = modelSnapshotGeneration;
		const pending = pendingModelRequests.get(account.id);
		if (pending?.generation === generation) return pending.request;

		const request = client
			.listProviderModels(account.id)
			.then((result) => {
				if (generation === modelSnapshotGeneration) {
					modelSnapshots.set(account.id, {
						models: result.models,
						expiresAt: now().getTime() + modelSnapshotTtlMs,
					});
				}
				return result.models;
			})
			.catch((error) => {
				if (snapshot) return snapshot.models;
				throw error;
			})
			.finally(() => {
				if (pendingModelRequests.get(account.id)?.request === request) {
					pendingModelRequests.delete(account.id);
				}
			});
		pendingModelRequests.set(account.id, { generation, request });
		return request;
	}

	async function listConfiguredModels(
		forceRefresh = false,
		accountSnapshot?: RoutingAccountView[],
		existingClient?: IRoutingNineRouterClient,
	) {
		if (!existingClient) await refreshRuntimeIfUnavailable();
		const client = existingClient ?? clientForRuntime();
		const accounts = (accountSnapshot ?? (await client.listAccounts())).filter(
			(account) => account.active,
		);
		if (accounts.length === 0) return [];

		const results = await Promise.allSettled(
			accounts.map((account) =>
				modelsForAccount(client, account, forceRefresh),
			),
		);
		const models = new Map<string, RoutingModelView>();
		let fulfilledAccounts = 0;
		let firstError: unknown;
		for (const result of results) {
			if (result.status === "rejected") {
				firstError ??= result.reason;
				continue;
			}
			fulfilledAccounts += 1;
			for (const model of result.value) {
				if (!models.has(model.id)) models.set(model.id, model);
			}
		}
		if (fulfilledAccounts === 0) throw firstError;
		return [...models.values()];
	}

	return {
		async getSettings(
			_userId: number,
			details: RoutingSettingsDetails = {},
		): Promise<RoutingSettingsView> {
			const settings = emptyRoutingSettingsView();
			const checkedAt = now().toISOString();
			const status = await refreshRuntimeIfUnavailable();
			settings.runtime = runtimeView(status, checkedAt);

			try {
				const client = clientForManagement();
				const accounts = await client.listAccounts();
				settings.runtime = runtimeView(
					{ ...status, state: "ready", lastError: null },
					checkedAt,
				);
				settings.accountSummary = {
					total: accounts.length,
					degraded: accounts.filter((account) =>
						["cooling", "limited", "failed"].includes(account.status),
					).length,
				};
				if (details.accounts) settings.accounts = accounts;
				if (details.models) {
					settings.models = await listConfiguredModels(false, accounts, client);
				}
			} catch (error) {
				const safeError = safeAppError(error);
				settings.runtime.status = "degraded";
				settings.runtime.capabilities.readAccounts = true;
				settings.runtime.lastError = {
					code: safeError.code,
					message: safeError.message,
					retryable: safeError.statusCode >= 500,
				};
			}
			return settings;
		},

		async listModels(_userId: number, forceRefresh = false) {
			return callSafely(() => listConfiguredModels(forceRefresh));
		},
		async listAccounts(_userId: number) {
			return callSafely(() => clientForManagement().listAccounts());
		},

		async getProvider(_userId: number, id: string) {
			return callSafely(() => clientForRuntime().getProvider(id));
		},
		async listProviderModels(_userId: number, id: string) {
			return callSafely(() => clientForRuntime().listProviderModels(id));
		},
		async startOAuth(userId: number, provider: string) {
			if (!dependencies.oauth) throw runtimeUnavailable();
			return dependencies.oauth.startAuthorizationCode(userId, provider);
		},
		async exchangeOAuth(
			userId: number,
			provider: string,
			input: { transactionId: string; state: string; code: string },
		): Promise<RoutingAccountView> {
			const oauth = dependencies.oauth;
			if (!oauth) throw runtimeUnavailable();
			const account = await callSafely(() =>
				oauth.completeAuthorizationCode(userId, provider, input),
			);
			expireModelSnapshots();
			return account;
		},
		async startDeviceCode(userId: number, provider: string) {
			if (!dependencies.oauth) throw runtimeUnavailable();
			return dependencies.oauth.startDeviceCode(userId, provider);
		},
		async pollDeviceCode(
			userId: number,
			provider: string,
			input: { transactionId: string },
		): Promise<RoutingOAuthPollingStateView> {
			const oauth = dependencies.oauth;
			if (!oauth) throw runtimeUnavailable();
			const result = await callSafely(() =>
				oauth.pollDeviceCode(userId, provider, input),
			);
			if (result.account) expireModelSnapshots();
			return result;
		},
		async cancelDeviceCode(
			userId: number,
			provider: string,
			input: { transactionId: string },
		) {
			if (!dependencies.oauth) throw runtimeUnavailable();
			return dependencies.oauth.cancelDeviceCode(userId, provider, input);
		},
		async listProviderNodes(_userId: number) {
			return callSafely(() => clientForRuntime().listProviderNodes());
		},
		async createProviderNode(
			_userId: number,
			input: CreateRoutingProviderNodeInput,
		) {
			const node = await callSafely(() =>
				clientForRuntime().createProviderNode(input),
			);
			expireModelSnapshots();
			return node;
		},
		async validateProviderNode(
			_userId: number,
			input: ValidateRoutingProviderNodeInput,
		) {
			return callSafely(() => clientForRuntime().validateProviderNode(input));
		},
		async updateProviderNode(
			_userId: number,
			id: string,
			input: UpdateRoutingProviderNodeInput,
		) {
			const node = await callSafely(() =>
				clientForRuntime().updateProviderNode(id, input),
			);
			expireModelSnapshots();
			return node;
		},
		async deleteProviderNode(_userId: number, id: string): Promise<void> {
			await callSafely(() => clientForRuntime().deleteProviderNode(id));
			expireModelSnapshots();
		},
		async createApiKeyAccount(
			_userId: number,
			input: CreateRoutingApiKeyAccountInput,
		) {
			const account = await callSafely(() =>
				clientForRuntime().createApiKeyAccount(input),
			);
			expireModelSnapshots();
			return account;
		},
		async updateAccount(
			_userId: number,
			id: string,
			input: UpdateRoutingAccountInput,
		) {
			const account = await callSafely(() =>
				clientForRuntime().updateAccount(id, input),
			);
			expireModelSnapshots();
			return account;
		},
		async deleteAccount(_userId: number, id: string): Promise<void> {
			await callSafely(() => clientForRuntime().deleteAccount(id));
			modelSnapshots.delete(id);
			expireModelSnapshots();
		},
		async testAccount(_userId: number, id: string) {
			const result = await callSafely(() => clientForRuntime().testAccount(id));
			if (result.refreshed) expireModelSnapshots();
			return result;
		},
	};
}
